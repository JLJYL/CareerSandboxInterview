STAR_LABELS: tuple[str, ...] = STAR_PART_KEYS + ("取捨", "其他")
"""分派用的標籤。

【為什麼要改成分派】
yes/no 加抄原文是存在性宣稱:找到一句就能說「有」,而任何一段話裡總找得到
一句可以被讀成任務的。說「沒有」反過來是全稱宣稱,要掃完整段才成立。
這個不對稱就是 T 一律答「有」的原因,換問法治不了。

分派把它變成互斥:一句只能掛一個標籤,要說「有任務」就得從「行動」那邊
搶一句過來,而行動的判讀是 1.00。搶錯會在行動那一欄顯示出來,
不會像單題問法那樣悄悄多出一個任務段。

【為什麼取捨要有自己的標籤】
第一輪分派把任務從 0.29 拉到 0.86,只剩 A7 失敗,而且 5/5 都把取捨那一句
掛成 T:「我判斷兩個月的時間只夠做一件事」讀起來就是一個目標。

同一份記錄裡,單題呼叫對同一句話的判讀是「取捨」而且正確。模型認得它,
是分派的標籤集合裡沒有它的位置——只能掛「其他」,而垃圾桶比不過
看起來很貼的 T。加上這個標籤之後任務是 1.00。

取捨這個**事實**還是從單題問法來(那一項一直是 1.00),這個標籤的唯一作用
是讓那句話有地方去,T 就沒東西可搶。
"""

LABEL_MEANING: dict[str, str] = {
    "S": "當時的背景或處境",
    "T": "他要達成什麼——別人交付給他的任務,或他自己的目標",
    "A": "他實際做了什麼",
    "R": "這件事最後怎麼樣",
    "取捨": "他放棄了什麼,以及當時的判斷依據",
    "其他": "以上都不是",
}
"""每個標籤的意思。鍵必須與 STAR_LABELS 一致,檔尾有檢查。"""


def _cols(text: str) -> int:
    """字串佔幾個等寬欄位。中文算兩格。"""
    return sum(2 if ord(c) > 0x2E7F else 1 for c in text)


def render_labels() -> str:
    """把標籤寫成 prompt 文字。清單從 STAR_LABELS 生出來,不另外手寫一份。"""
    width = max(_cols(v) for v in STAR_LABELS) + 2
    return "\n".join(
        f"    {v}{' ' * (width - _cols(v))}{LABEL_MEANING[v]}" for v in STAR_LABELS
    )


ASSIGN_SYSTEM = f"""你在讀一段面試回答,把每一句分派到一個標籤。只分派,不評價。

【標籤】

{render_labels()}

【規則】

**一句只能掛一個標籤。** 一句話同時像行動又像任務的時候,挑比較貼的那一個,
不要兩個都給。掛不上去的掛「其他」。

一句話在講「我當時決定放掉什麼」的時候掛「取捨」,不要掛 T——
那是他自己做的取捨,不是別人交付給他的任務。

標籤不必用完。一段回答裡沒有任務段是很常見的——那就沒有任何一句掛 T,
不要為了把標籤用完而硬塞。

【輸出格式】

只回這個 JSON,鍵是句子編號的字串,值是 {" / ".join(STAR_LABELS)} 其中之一:

{{"1": "S", "2": "A", "3": "R"}}

每一句都要出現,一句都不能漏。"""


def assign_user_message(sentences: list[str]) -> str:
    listed = "\n".join(f"{i}. {s}。" for i, s in enumerate(sentences, 1))
    return f"【他剛剛說的,一句一行】\n{listed}"


