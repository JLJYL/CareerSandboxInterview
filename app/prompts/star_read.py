"""讀一段回答裡有哪些事實:STAR 四段、結果有沒有數字、有沒有取捨、有沒有自述困難。

【這個檔只負責「有什麼」,不負責「夠不夠」】
夠不夠是 `AcceptRule` 的事,而那是程式算的。1d 實測的結論是放行條件
寫進 prompt 兩次都沒生效:三種難度的追問率都是 0.500,而「有沒有可查證的
數字」這一個 bit 就能預測 180/180 次決定——模型在看那一個訊號,
不是在對照條件。

所以判斷搬回程式,模型只剩供應事實這一件事。這是「能用程式算的不要問 LLM」
在這裡的形式:它讀得準的部分留給它,它讀不準的部分不要問。

【每一題都要抄原文】
封閉集合那一輪的教訓:給選單又附說明,模型會挑一個然後把說明背出來。
`缺情境` 在 A2 與 A3 上出現 20 次,而那兩筆的第一句就是情境,
`why` 幾乎逐字抄 prompt 裡的選項註解。而且越嚴的難度編得越兇
(新手 0 次、中等 4 次、困難 16 次)。

要求抄原文把這件事堵住兩層:抄不出原文就是沒有;抄出來的句子程式可以
直接驗是不是真的在答案裡。第二層才是重點——自述沒辦法驗,引文可以。

【跟報告那支 STAR 的分工】
`compose_star_prompt()` 讀整份逐字稿,產出報告要呈現給使用者的 STAR 四段,
用 gpt-4o 要求逐字引文。這裡讀的是**單一輪的回答**,產出的是決定要不要
追問的輸入,用 gpt-4o-mini。輸入、模型、消費端三樣都不同,所以沒有合併——
合併就會變成報告的呈現需求去牽動每一輪的決定。

【實測依據】
`tools/star_read_eval.py`。六項事實在 210 次判讀下全部 1.00,
引文落地 130/130。拆成六次問與一次問六題的差距是 0.00,
所以不拆;任務那一項是靠句子分派從 0.29 救到 1.00 的,見 STAR_LABELS。
"""

from __future__ import annotations

from app.pipeline.interviewer_spec import STAR_PART_KEYS, STRUGGLE_FACT

FACTS: tuple[str, ...] = STAR_PART_KEYS + ("quantified", "tradeoff", STRUGGLE_FACT)
"""要判讀的七件事。前四個直接取 `STAR_PART_KEYS`,不另寫一份。

第七項的鍵名取 `interviewer_spec.STRUGGLE_FACT`,不在這裡再寫一次字串:
那個鍵是派發端(`turn_decision.struggle_dimension`)讀的,兩邊寫兩份,
哪天只改了一邊,派發會靜默退回休眠狀態而不是報錯。
"""
FACT_NAME: dict[str, str] = {
    "S": "情境",
    "T": "任務",
    "A": "行動",
    "R": "結果",
    "quantified": "量化",
    "tradeoff": "取捨",
    STRUGGLE_FACT: "自述困難",
}
"""報表與 log 用的中文名。鍵必須與 FACTS 一致,檔尾有檢查。"""

FACT_QUESTION: dict[str, str] = {
    "S": "這段回答有沒有交代當時的背景或處境——事情是在什麼情況下發生的?",
    # 原本問「有沒有交代他要達成什麼」,單題問法在 T 不存在的四筆上 0.00——
    # 每一次都答「有」。一題單獨問,任何回答都能被讀成隱含一個目標:
    # 「我把訂單資料接進資料庫」可以解釋成「目標是自動化報表」,
    # 然後抄行動那句話當證據。引文落地率 100% 配上準確率 0.33,
    # 說明抄原文消滅的是編造證據,不是張冠李戴。
    #
    # 改問法沒用(這段文字已經是第二版,把第一版 0.70 改成 0.29)。
    # 真正有效的是改格式,見 ASSIGN_SYSTEM。這段留著是因為無標點的逐字稿
    # 切不出句子,那時只剩單題問法可用——那條路徑上 T 本來就是不可靠的,
    # 由 `AnswerFacts.read_by` 標出來。
    "T": (
        "他有沒有**說出**別人要他做什麼,或者他當時的目標是什麼?"
        "只算他明講的那一句。"
        "不要從他做了什麼回頭推論目標——「我做了 X」不等於「我的任務是 X」。"
    ),
    "A": "這段回答有沒有交代他自己實際做了什麼?",
    "R": "這段回答有沒有交代最後怎麼樣——這件事的結果?",
    "quantified": "這段回答講的結果裡,有沒有可查證的數字?",
    "tradeoff": "這段回答有沒有交代他放棄了什麼,以及當時的判斷依據?",
    # 這一項只有單題問法可用:它不是 S/T/A/R 四段裡的一段,是整段回答的性質,
    # 句子分派沒有標籤可以掛。T 那一項的前車之鑑是——寬問句、單題、是非加抄原文,
    # 三樣湊在一起會一律答「有」。所以問句寫窄:只算他明講的那一句,
    # 並且把兩種最容易被誤讀成「有」的情況在問句裡直接排除。
    STRUGGLE_FACT: (
        "他有沒有**說出**他自己哪裡做不好、哪裡卡住、或哪個部分還不夠?"
        "只算他明講的那一句。"
        "只講做成了什麼不算;講別人或外部條件造成的困難也不算——"
        "那是情境,不是他自己的不足。"
    ),
}


FACT_RULES = """你在讀一段面試回答,只回報事實,不評價好壞,不給建議。

【抄原文的規則】

說「有」的時候,一定要從回答裡抄一句原文當證據,一字不改。
抄不出原文就是「沒有」。不要改寫、不要摘要、不要自己補上他沒說的話。"""


FACT_OUTPUT = """【輸出格式】

只回這個 JSON,不要加任何說明文字:

{"present": true, "quote": "從回答裡抄的一句原文"}

    present  true 或 false
    quote    present 為 true 時必填,一字不改地抄。false 填空字串。"""


def compose_fact_prompt(fact: str) -> str:
    """一次只問一件事的 system prompt。"""
    return "\n\n".join(
        [FACT_RULES, f"【這一次只判斷一件事】\n\n{FACT_QUESTION[fact]}", FACT_OUTPUT]
    )


def fact_user_message(answer: str) -> str:
    return f"【他剛剛說的】\n{answer}"


