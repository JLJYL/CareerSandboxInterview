"""漏講點(A5)的生成規則。

【A5 在做什麼】
面試結束後告訴使用者:「你履歷上有、這份 JD 也要、但你這場沒講到的點」。
每一條附一句 why——為什麼這一點對這份 JD 重要。

【分工】
成員 A 的 GapComputer 算出候選(三集合差集,確定性)。
這裡只負責兩件事:
    1. 替每條候選寫 why
    2. 否決撐不住的候選

【why 只能寫 JD 側,這是鐵則】
實測 GapCandidate 的證據強度極不對稱:

    履歷證據  「C#」                                    ← 只有標籤
    JD 證據   「MES系統與周邊系統程式維護、C#程式開發與問題排除」  ← 完整句子

履歷側之所以弱,是因為 persona 的技能全部掛在 experiences[0].tags,
標籤與經歷的對應關係不可靠。用它敘事會產生錯誤歸因,而且錯得很具體
——「你在圖書館志工經歷中展現了進度控管」讀起來完全合理,但可能是錯的。

所以 why 一律從 JD 側論證。定義同步在
app/contracts/interview_protocols.py 的 WHY_MUST_BE_JD_SIDE。
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# why 的寫法
# ---------------------------------------------------------------------------

WHY_RULES = """替每一個漏講點寫一句 why,說明它對這份 JD 為什麼重要。

材料只有一個:jd_evidence,也就是這份 JD 裡提到這項能力的原文。

寫法:
    一到兩句,四十到八十字。
    指出這份 JD 在什麼脈絡下需要這項能力。
    可以引用 jd_evidence 的關鍵字,但不要整句照抄。

嚴禁:
    敘述使用者在哪一段經歷做了什麼。經歷與技能的對應關係不可靠,
    敘事會產生看起來很具體、但可能完全錯誤的歸因。
    使用 resume_evidence 的內容。那通常只是一個標籤,撐不起任何敘述。
    寫成建議句(「你應該多提到…」)。why 回答的是「為什麼重要」,
    不是「你該怎麼做」。
    誇大重要性。JD 只提一次的能力,不要寫成「這是本職位的核心」。"""


# ---------------------------------------------------------------------------
# 否決機制
# ---------------------------------------------------------------------------

WHY_SCOPE = """你的工作只有一件:替每一個候選寫一句 why。

**不要判斷哪些該保留、哪些該剔除。** 每一條都要寫。

【為什麼不要你判斷】
早期版本讓模型同時做否決與寫理由,實測結果:
    不經模型   17 條候選,7 條是真漏講   precision 0.412
    經過模型   10 條保留,4 條是真漏講   precision 0.400
否決掉的 7 條裡有 3 條是真漏講,留下的 6 條全是假指控,
而且否決的位置集中在候選清單後段——那是注意力衰減,不是判斷。

過濾這件事有更可靠的做法(語意比對、履歷條件式模糊匹配),
不該靠寫理由的同一次呼叫順便做。

【沒有例外】
清單裡有幾條,你就回幾條理由。不要少回,不要多回,不要跳過任何一條。
材料不足的候選在送到你這裡之前就已經被程式濾掉了,
所以你看到的每一條都寫得出理由。"""


# ---------------------------------------------------------------------------
# 輸出格式
# ---------------------------------------------------------------------------

OUTPUT_FORMAT = """輸出一個 JSON 陣列。**每個元素必須帶 id**,對應輸入候選的編號。

    [
      {"id": 1, "why": "這份職缺把資料查詢列為日常工作…"},
      {"id": 2, "why": "…"},
      {"id": 3, "why": "…"}
    ]

只有 id 與 why 兩個欄位,沒有其他欄位。
id 必須是輸入清單裡的編號,每一個編號都要出現一次,不多不少。

不要有任何其他文字、說明、前言或 markdown 標記。陣列本身就是完整輸出。

【為什麼沒有 keep 欄位】
早期版本讓模型回 keep 決定要不要保留。實測兩輪,模型否決的位置集中在
候選清單後段——那是注意力衰減,不是判斷,而且被砍掉的多半是正確的項目。
過濾不是這一層的工作,所以連表達否決的欄位都不提供。

【id 為什麼是必要的】
更早的版本靠陣列位置對齊,模型多輸出一個元素就整批位移一格,
結果是理由被安到別的技能上。id 讓錯位不可能發生。"""


WHY_STYLE = """why 的寫法還有三條:

1. 不要用固定句型。
   「這份 JD 明列需要 X」連寫五條會讓整份回饋看起來像模板。
   每一條的切入點應該不同——有的講這項能力在什麼工作環節被用到,
   有的講它跟其他需求的關係,有的講這份 JD 為什麼特別強調它。

2. 用台灣的繁體中文用語。
   使用者介面(不是用戶界面)、互動(不是交互)、程式碼(不是代碼)、
   資料庫(不是數據庫)、專案(不是項目)、軟體(不是軟件)、效能(不是性能)。

3. 不要提到使用者做過什麼。
   不論主詞是「你」「候選人」「應徵者」,不論名詞是「經歷」「專案」
   「專題」「實習」——只要句子在描述使用者做過的事,就違規。
   why 只講這份 JD 為什麼需要這項能力。"""


MAX_POINTS = 5
"""最多回報幾條漏講點。

依據:前端 InterviewReportScreen 的漏講點區塊是列表顯示,超過五條會需要
捲動,而且使用者記不住。候選已依 weight 排序,取前 N 條即可。

這個截斷發生在否決之後——先讓 LLM 判斷,再取前五條,
不是先取五條再判斷(那樣被否決的位置就浪費了)。
"""


def compose_why_prompt() -> str:
    """組成 system prompt。"""
    return "\n\n".join(
        [
            "你的工作是替面試回饋裡的「漏講加分點」寫理由,並否決撐不住的項目。",
            WHY_SCOPE,
            WHY_RULES,
            WHY_STYLE,
            OUTPUT_FORMAT,
        ]
    )
