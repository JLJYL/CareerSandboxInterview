def compose_collab_prompt(dimension: str, *, has_excerpts: bool = True) -> str:
    """單一維度的 BARS prompt。

    一個維度一次呼叫。合併評四個會讓分數黏在一起(r̄ ≈ .86–.92),
    那個相關高到四個分數等於同一個分數。
    """
    parts = [f"你的工作是替團體面試的「{dimension}」這個維度評分。", COMMON]
    body = BARS.get(dimension)
    if body:
        parts.append(body)
    parts.append(OUTPUT if has_excerpts else UNAVAILABLE)
    return "\n\n".join(parts)


