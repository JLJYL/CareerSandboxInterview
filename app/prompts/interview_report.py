def compose_face_prompt() -> str:
    return "\n\n".join([
        "你的工作是替一場模擬面試寫三個面向的評語與建議。",
        COMMON_RULES, STT_CAVEAT, FACE_RULES, FACE_OUTPUT,
    ])


def compose_sub_score_prompt() -> str:
    """表達流暢度不在這裡產出,由 score_fluency() 依填充詞率計算。

    能用公式算的不要問 LLM。實測:填充詞每百字 3.0(正常區間)時
    模型給流暢度 71,分數沒有跟著錨走。單調映射不會有這個問題。
    """
    return "\n\n".join([
        "你的工作是替一場模擬面試打細分分數。",
        COMMON_RULES, STT_CAVEAT, SUB_SCORE_RULES, SUB_SCORE_OUTPUT,
    ])


def compose_question_prompt() -> str:
    """better 不再分「有履歷」與「無履歷」兩種模式。

    有履歷模式是捏造的通道,而且它做的事跟漏講點區塊重複——
    「你履歷有但沒講到」本來就是 A5 的工作。拿掉之後 better 變成可驗證的:
    裡面的每個事實都必須來自那一題的回答。
    """
    return "\n\n".join([
        "你的工作是替一場模擬面試逐題寫點評與更好的講法。",
        COMMON_RULES, STT_CAVEAT, QUESTION_RULES, QUESTION_OUTPUT,
    ])


def compose_star_prompt() -> str:
    return "\n\n".join([
        "你的工作是把使用者講的經歷拆成 STAR 四段。",
        COMMON_RULES, STT_CAVEAT, STAR_RULES, STAR_OUTPUT,
    ])


MAX_IMPROVEMENTS = 4
"""improvements 最多幾條。由 faceDimensions 的 points 彙整,不另打 LLM。

不另打 LLM 的兩個理由:省一次呼叫;讓建議與評語必然一致——
分開產生的話,三維面向說「補上數字」而 improvements 說「講慢一點」,
使用者會不知道該聽哪一個。
"""
