"""面試報告(A4)的生成規則。

【六個區塊的分工】
    faceDimensions    三維面向,LLM 寫 verdict 與 points,分數部分錨定
    subScores         六項固定名稱,能錨的錨在 TextStats 上
    questionFeedbacks 逐題點評與更好的講法
    starParts         S/T/A/R 四段,fromAnswer 必須是逐字稿原文
    improvements      由 faceDimensions 的 points 彙整,**不打 LLM**
    collabDims        僅群面,等後端組的 rubric,本期不產出

【A5 學到的三件事,這裡沿用】
一、不讓 LLM 做它做不穩的事。分數、計數、過濾都不可靠。
二、固定值域靠機械修復,不靠 prompt 自律(repair_report 已經在做)。
三、要讓一個機制不存在,不能留開關、欄位或例外。
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 共用
# ---------------------------------------------------------------------------

COMMON_RULES = """通用規則:

1. 用台灣的繁體中文。使用者介面、互動、程式碼、專案、資料庫、軟體、效能。

2. 對象是正在練習面試的學生。語氣直接、具體、可行動,不要客套。
   「你的回答缺少數字」比「整體表現尚可,惟仍有進步空間」有用。

3. 只根據逐字稿裡實際出現的內容評論。
   逐字稿沒有的事不要推測,不要因為「這種職位通常會問到 X」就假設他講過或沒講過。

4. 不要宣稱你測量了無法測量的東西。
   沒有音訊,所以不知道語速、音量、語調。
   沒有影像,所以不知道眼神、表情、姿態。
   這些一律不提。"""


STT_CAVEAT = """關於逐字稿的品質:

這份逐字稿來自 Android 裝置端語音辨識,有三個已知特性:

    沒有標點符號。句子邊界是說話停頓造成的分段,不是文法句號。
    英文技術詞常被轉錯。JavaScript 可能寫成「加巴screen」,Git 可能寫成「gats」。
    非詞彙填充音(嗯、呃)會被引擎移除,詞彙型的(那個、就是、然後)保留。

所以:

    不要因為用詞奇怪就評論「表達不清楚」——那可能是辨識錯誤。
    不要評論標點使用或句子長短。
    不要說「你講話不流暢」如果證據只是斷句破碎。"""


# ---------------------------------------------------------------------------
# 三維面向
# ---------------------------------------------------------------------------

FACE_RULES = """產出三個面向的評語與建議:內容、結構、表達。

每個面向要有:
    verdict   一句總評,二十到四十字,指出這個面向最明顯的一個特徵
    points    一到三條可行動的建議,每條十五到三十字,寫成祈使句

三個面向各自看什麼:

    內容   講了什麼。有沒有具體事例、有沒有數字、有沒有落到自己做的事上。
    結構   怎麼組織。有沒有先講結論、段落之間有沒有邏輯關係、有沒有交代結果。
    表達   怎麼說。用詞是否精準、有沒有冗贅、有沒有停在重點上。

points 的寫法:

    好   自我介紹時先給一個量化成果,再展開背景
    好   講經歷時補上結果那一段,不要停在做了什麼
    壞   建議加強表達能力
    壞   可以更有自信一些

差別在於好的那些**照著做得出來**,壞的那些只是形容。"""


# ---------------------------------------------------------------------------
# 六項細分分數
# ---------------------------------------------------------------------------

SUB_SCORE_RULES = """給細分分數,每項 0 到 100。

【分數的意義】
    85 以上  明顯是強項,舉得出具體證據
    70–84    正常水準,有改進空間但不扣分
    55–69    有明顯缺口,是這場的主要問題之一
    55 以下  幾乎沒有表現

【要拉開差距】
全部落在同一個十分區間代表沒有分辨。一場面試裡強項與弱項通常差二十分以上。
先決定最強與最弱的那兩項,其餘再往中間排。

【沒有數字的項目是印象分】
互動能力與應變能力沒有可測訊號,給分往中間靠,不要輕易給 90 以上或 50 以下。"""


# ---------------------------------------------------------------------------
# 逐題回顧
# ---------------------------------------------------------------------------

QUESTION_RULES = """逐題產出兩段:

    comment  這一題答得如何,三十到六十字。指出一個具體的優點或問題,不要兩者都寫。
    better   同樣的內容可以怎麼講得更好,四十到八十字。直接寫出可以照著念的句子。

【better 只能重組,不可以新增任何事實】

材料**只有這一題的回答本身**。允許的動作:

    把結論提前
    補上 STAR 的結構詞(當時的情況是…我負責…我做的是…結果是…)
    去掉冗詞與重複
    把模糊的說法講精確——但只能用回答裡已經有的資訊

嚴禁:
    新增回答裡沒有的數字。
    回答說「約訪談的時間」,不可以寫成「訪談了三位消費者」。
    新增回答裡沒有的結果。
    回答說「產出一份企劃書」,不可以寫成「這份企劃書後來被用於實際的行銷活動」。
    新增公司名、學校名、職稱、工具名、時間長度。
    把「我有做過」升級成「我主導」,除非回答裡就是這樣說的。

【為什麼這條特別嚴】
使用者會把 better 背下來,拿去真正的面試講。你補的那個數字他答不出後續追問,
因為那件事沒發生過。這比履歷造假更嚴重——履歷是他自己寫的,better 是我們給的。

【「你其實還可以提到 X」不是這裡的工作】
使用者履歷上有、但這場沒講到的東西由漏講點區塊負責,不要寫進 better。
兩邊都做會重複,而且 better 這一側沒有履歷可以查證。

【檢查】
系統會抽出 better 裡的所有數字,逐一比對是否出現在原回答中。
對不上就整條丟掉。與其被丟掉,不如一開始就不要加。"""


