STAR_RULES = """把使用者講經歷的部分拆成 STAR 四段:

    S 情境 Situation   背景是什麼、在什麼場合
    T 任務 Task        他要達成什麼、負責哪一塊
    A 行動 Action      他實際做了什麼
    R 結果 Result      結果如何、學到什麼

每一段判斷有沒有講到:

    有講到   present=true,fromAnswer 填**逐字稿裡原封不動的那一句**
    沒講到   present=false,fromAnswer 留空,hint 寫這一段該補什麼

【fromAnswer 是原文引用,這條是硬性要求】
必須是逐字稿裡真的出現過的連續文字,一個字都不能改。
不要修正錯字,不要補標點,不要把兩句話接起來,不要改寫成通順的版本。
逐字稿寫「我沒先測試就直接全推」,你就填「我沒先測試就直接全推」。

系統會逐字檢查這一段是不是逐字稿的子字串,對不上就整條丟掉。
找不到剛好對應的句子時,寧可判 present=false,不要湊一句。

【T 與 A 的切分,這一段特別容易錯】
中文描述經歷時,任務與行動常出現在同一句裡,要拆開:

    原句「我在這個專案裡面負責的部分主要是前端的設計,
          用 Kotlin 去開發這些頁面跳轉的邏輯還有按鈕點擊的回饋」

    T   我負責的部分主要是前端的設計        ← 被交付的責任範圍
    A   用 Kotlin 去開發頁面跳轉的邏輯      ← 實際採取的動作

判準:
    T 回答「你要達成什麼、負責哪一塊」——責任、目標、期限、範圍
    A 回答「你實際做了什麼」——具體的動作、用了什麼方法或工具

「我負責 X」是 T,不是 A。「我用 Y 做了 Z」才是 A。

實測十格,T 有 9 格被判成缺,其中多數是因為整句被算成 A 了。
T 與 A 出現在同一句時,fromAnswer 各取那一句的**不同片段**,
不要因為它們在同一句就只填一個。

【hint 的寫法】
指出該補什麼內容,不是評論。
    好   缺結果:補上這件事最後怎麼了,以及你從中學到什麼
    壞   結果段落表現不佳,建議加強"""


