"""逐題情緒:這一題回答的時候他是什麼狀態。

【這一塊不進分數】
情緒進分數等於「緊張的人分數比較低」。產品定位是練習回饋不是能力評估,
效度上限本來就低,再加一個主觀變項只會更低。

所以它在報告裡跟六項分數並列但不參與計算,而且**平穩不標註**——
報告只在特別需要的時候講一句,不是每一題都掛一個情緒標籤。

【逐題,不累積】
不接 CoMPM 的累積狀態那一半。情緒還在決定追問策略的時候,
「這位說話者累積到現在的狀態」是有用的輸入;改成逐題回饋之後,
獨立比累積重要——使用者記得的是「我答那一題的時候很卡」,
不是「我整場的情緒曲線」。

【為什麼用分派而不是逐題問是非】
決策那一輪實測出來的:yes/no 加抄原文是存在性宣稱,找到一句就能說「有」,
而任何一段話裡總找得到一句可以被讀成焦慮的。任務那一項在不存在的四筆上
0.00——不是偶爾錯,是每次都答「有」。

情緒的方向更糟:把一個人標成焦慮是對他的判斷,而誤標的代價比
「少講一個缺結果」高得多。所以用互斥的分派,而且預設落在平穩:
要說焦慮就得從平穩那邊搶過來,搶錯會在別的題上顯示出來。

【為什麼一定要抄原文】
`報告裡怎麼寫` 那一欄要求引一句原文,而那同時是查證手段:它說他焦慮
可以是編的,但它抄的那句話在不在原文裡,程式查得出來。
抄不出來就退回平穩,不標註。
"""

from __future__ import annotations

EMOTION_LABELS: tuple[str, ...] = ("平穩", "焦慮", "卡住", "過度自責")
PLAIN = EMOTION_LABELS[0]
"""四種狀態,封閉集合。`平穩` 是預設,而且不標註。

值域宣告出來是為了前端:它照標籤決定要不要畫那一行。
多一個值而它沒跟著加,那一題會變成什麼都不顯示而不是顯示未知。
"""

EMOTION_SIGNAL: dict[str, str] = {
    "平穩": "句子完整、有具體內容",
    "焦慮": "句子斷得碎、反覆改口",
    "卡住": "長停頓、明確說不知道",
    "過度自責": "反覆否定自己",
}
"""每一種的判讀依據。鍵必須與 EMOTION_LABELS 一致,檔尾有檢查。

【哪幾個訊號不能照字面用】
`句子斷得碎` 與 `長停頓` 都受轉錄引擎影響,不只受他的狀態影響:

    裝置端引擎沒有標點、會漏字,所以「斷得碎」是引擎的性質
    打字的回答沒有停頓資料,所以「長停頓」在那個模式下不存在

這跟表達流暢度踩過的坑是同一個:打字的答案標點乾淨就拿到高流暢度。
所以 prompt 裡會按輸入模式把不適用的訊號講清楚,不是讓模型自己判斷。

`明確說不知道` 是唯一程式算得出來的——`interview_live._ADMITS_UNKNOWN`
那組字面。那一項不問模型。
"""

EMOTION_WRITEUP: dict[str, str] = {
    "平穩": "不標註",
    "焦慮": "標註哪一題,引一句原文",
    "卡住": "標註哪一題,引一句原文",
    "過度自責": "標註哪一題,只描述行為不評價",
}
"""報告裡怎麼寫。鍵必須與 EMOTION_LABELS 一致。

`過度自責` 那一條是刻意跟前兩個不同的:引一句「我真的很爛」回去給使用者看,
不是回饋是傷害。所以那一類只描述行為(「有幾次回頭否定自己」),不引原文。
"""


EMOTION_MARK = "判斷他回答每一題的時候是什麼狀態"
"""這支 prompt 的辨識字串。

【為什麼要宣告一個】
假 LLM 都用 system prompt 的片段派發回應,而這一塊第一版的開頭含「逐題」,
跟逐題點評那一塊撞號——情緒的呼叫會拿到點評的陣列,解析成空的,
然後報告少一整塊而測試全綠。同一類問題這是第三次
(1c 的決策分支、2c 的事實分支)。

所以辨識字串由這裡宣告,測試 import 它,不自己抄一段。
抄的那一段跟 prompt 漂開的時候,漂掉的方向永遠是「悄悄沒接上」。
"""

EMOTION_TASK = f"""你在讀一場模擬面試,{EMOTION_MARK}。

只回報狀態,不評價好壞,不給建議,不猜原因。"""


def render_labels() -> str:
    """把封閉集合寫成 prompt 文字。清單從 EMOTION_LABELS 生出來,不另外手寫一份。"""
    width = max(len(v) for v in EMOTION_LABELS) * 2 + 2
    return "\n".join(
        f"    {v}{' ' * (width - len(v) * 2)}{EMOTION_SIGNAL[v]}" for v in EMOTION_LABELS
    )


SIGNAL_BY_MODE: dict[str, str] = {
    "voice": """【這些回答是講出來的】

斷句與停頓有意義,但要分清楚是誰造成的:逐字稿由語音辨識產生,
裝置端引擎會漏字、沒有標點,那是引擎的性質不是他的狀態。

**只有同一份逐字稿裡某幾題明顯比其他題碎,才算訊號。** 整場都碎就是引擎。""",
    "typed": """【這些回答是打出來的】

沒有停頓資料,也沒有辨識誤差。所以「長停頓」這個訊號在這裡不存在,
不要從句子長短推論他停頓了多久。

打字的回答標點乾淨是必然的,不代表他平穩。要看的是內容:
反覆改口會留下痕跡(寫了又改的句式),明確說不知道會寫出來。""",
    "unknown": """【不確定這些回答是講的還是打的】

斷句與停頓都不可靠,所以那兩個訊號不要用。
只從內容判斷:明確說不知道、反覆否定自己。""",
}
"""輸入模式決定哪些訊號可用。

這一段不是客套,是在擋一個已經發生過的錯誤類型:四個測量的有效性取決於
`input_mode`,而那一欄沒被看進去的時候,打字的回答會因為標點乾淨
拿到高流暢度。情緒這一塊的「斷得碎」「長停頓」是同一個陷阱。
"""


EMOTION_OUTPUT = """【輸出格式】

只回這個 JSON,不要加任何說明文字。鍵是題號的字串:

{"1": {"label": "平穩", "quote": ""}, "2": {"label": "焦慮", "quote": "那個、那個我想一下"}}

    label  上面四個其中一個,一字不差。判斷不出來就填「平穩」。
    quote  label 不是「平穩」時必填,從那一題的回答裡抄一句原文,一字不改。
           抄不出原文就把 label 改成「平穩」。「平穩」時填空字串。

每一題都要出現,一題都不能漏。

**一題只有一個狀態。** 同時像焦慮又像卡住的時候挑比較貼的那一個。
判斷不出來就是「平穩」——那是預設,不是最後的選項。"""


def compose_emotion_prompt(input_mode: str = "unknown") -> str:
    """逐題情緒的 system prompt。

    不帶人格也不帶職缺:這一塊問的是「他當時是什麼狀態」,
    跟誰在問、這個職位要什麼都無關。帶了只會把 prompt 撐長。
    """
    return "\n\n".join(
        [
            EMOTION_TASK,
            f"【四種狀態】\n\n{render_labels()}",
            SIGNAL_BY_MODE.get(input_mode, SIGNAL_BY_MODE["unknown"]),
            EMOTION_OUTPUT,
        ]
    )


def emotion_user_message(rows: list[tuple[str, str, str]]) -> str:
    """把逐題問答擺成 user 訊息。rows 是 (題目, 回答, 停頓那一行)。

    停頓那一行是實測值,只有語音且前端有送段落結束時點的時候才有。
    沒有的時候整行不出現——印一行「停頓:無資料」會讓模型以為那是
    「沒有停頓」,而兩者差別很大。
    """
    body = ["【逐題內容】"]
    for i, (question, answer, pause_note) in enumerate(rows, 1):
        body += [f"{i}. 題目:{question}", f"   回答:{answer}"]
        if pause_note:
            body.append(f"   停頓:{pause_note}")
    return "\n".join(body)


_bad = set(EMOTION_LABELS) ^ set(EMOTION_SIGNAL) | set(EMOTION_LABELS) ^ set(
    EMOTION_WRITEUP
)
if _bad:
    raise RuntimeError(
        f"EMOTION_LABELS 與判讀依據/報告寫法對不上:{sorted(_bad)}。"
        "加一種狀態就要同時給它訊號與寫法,否則 prompt 會印出空白,"
        "而報告端不知道該不該標註它。"
    )
