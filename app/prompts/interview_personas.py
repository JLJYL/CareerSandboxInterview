#: 東西,另外三段都退回「有沒有遇到什麼挑戰」。字面比對看不出那件事——
#: 它每次換詞,所以重疊低而內容空。
#:
#: 原因在舊的 stance 寫的是**回答裡要出現的題材**(團隊、摩擦)。技術主管的
#: 「方法站不站得住」與用人主管的「為什麼選這個」幾乎每段回答都踩得到,
