#: 【四次量測的結論:字面問句是唯一會傳遞的東西,但它是被貼上去的】
#: 【不要再改這段文字去追那個數字。理由在最後一節。】
#: 同一份工具、同樣 3 rounds × 四段回答 × 三位,只有 HR 的 stance 在變:
#:
#:     v2  只關心團隊/摩擦        角色效果 0.363
#:     v3  四個角度(題材)        0.343   HR 十二題命中 1
#:     v4  主詞過濾規則 + 兩切法   0.374   HR 十二題命中 2
#:     v5  兩個字面問句(現行)    0.340   HR 十二題命中 3
#:
#: 四次 0.363 / 0.343 / 0.374 / 0.340,全距 0.034,而同一次裡四段回答之間
#: 的差距是 0.19–0.47。也就是說這四個數字分不開,三次改寫都沒有移動總體。
#:
#: 前兩次各被繞過一次:
#:
#: v3 的四個角度是**題材**,被吸收進技術主管的「怎麼判斷」框架,六次。
#:
#: v4 的規則寫「問題的主詞必須是他這個人」,結果十二題裡六題寫成
#: 「你當時是怎麼決定優先做那三個欄位的呢」——中文裡「你」就是主詞,
#: 規則形式上過關,問的還是欄位。判準下錯位置:該管的是問句在問什麼,
#: 不是誰當主詞,而「在問什麼」這件事沒辦法用一條規則讓模型自己檢查。
#:
#: 禁令那條(「不要退回去問有沒有遇到什麼挑戰」)也沒有效果。兩次 FOLLOW_UP
#: 合計:HR 有禁令 2/24,技術與用人沒禁令 3/44。差不多,所以它只是在一支
#: 已經 2500 字的 prompt 裡多佔位置。v3 那次的 0/30 是我拿一輪當結論,錯了。
#:
#: 真正傳遞的是形狀。v4 唯一一題問到人的,是照抄語氣示範來的——
#: 「你當下實際說了什麼」字元重疊 100%。而另外兩位一直穩,它們的 stance
#: 本來就是兩句話配一個字面問句:「那個結論怎麼來的」、「代價是什麼」、
#: 「為什麼選這個而不是那個」。
#:
#: 所以 v5 把 HR 改成跟它們同一個形狀:兩句話,裡面兩個字面問句,其餘刪掉。
#: 刪掉的是量過沒作用的東西(主詞規則、那句禁令),不是還沒驗證的東西。
#:
#: 【v5 的結果:形狀會傳遞,但只在一段回答上,而且是整句貼上去的】
#: 跑之前先講好的判準:「怎麼決定/評估 X」要從 6/12 掉到 2 以下,
#: 兩個形狀至少出現兩次。結果 3/12(腰斬,但沒過我自己設的那條線)、
#: 形狀出現 3 次。所以照先前講好的,這段文字不再改第四次。
#:
#: 細看比總分有用,逐格對 v4:
#:
#:                  角色效果        HR 貼合度
#:     團隊衝突   0.477 → 0.191   0.427 → 0.273   ← 形狀打中的那一格
#:     數據分析   0.308 → 0.365   0.300 → 0.333
#:     取捨決定   0.371 → 0.329   0.436 → 0.364
#:     泛泛而談   0.342 → 0.474   0.269 → 0.439
#:
#: 形狀打中的地方效果很大:HR 不再跟技術主管一起問那三個欄位,那一格的
#: 角色重疊掉了一半以上。但同一格的貼合度也跟著掉——因為它是**一字不差
#: 貼上去的**:「那件事對你來說最難的是哪一段?」三輪三次完全相同,
#: 沒有一個字來自那段回答。另一個形狀(「你怎麼知道自己那次做得好」)
#: 零次。
#:
#: 而且只在團隊衝突那一段打中。數據分析是一段順利的成功敘事,沒有明顯
#: 「難的地方」可指;取捨那段最突出的東西是那個決定本身。兩段都回到
#: 「有沒有遇到什麼挑戰」與「怎麼評估優先順序」。
#:
#: 【為什麼停在這裡】
#: 三次改寫、四次量測,總分沒動。可以傳遞的只有字面問句,而字面問句會被
#: 整句貼上,貼上就不咬回答——那是另一個問題,不是把句子寫得更好能解的。
#:
#: 還有一件事值得先確認再花力氣:這份工具用 `force_speaker` 把三位都塞到
#: 同一段回答上,生產環境不會這樣。團隊衝突在生產會派給 HR,數據分析會派
#: 給技術主管,所以 v4 最糟那一格(HR 與技術撞在同一個欄位問題上)根本
#: 不會發生。要證明生產裡真的「問題差不多」,要跑真實派發路徑。
#:
#: 【語氣示範會被照抄,這裡是刻意的】
#: `PersonaSpec.sample_lines` 的註解說示範最好跟這場面試無關,照抄就會明顯
#: 不合。那是為了擋「抄了也看不出來」的情況。這裡反過來用:HR 的示範現在
#: 就是我們要的問句形狀,而且四句都不綁特定題材,所以抄中也成立。
#:
#: 【第二版的四個角度沒生效,換成一條過濾規則加兩個切法】
#: v3(36 筆,`data/panel_v3.json`)量到的:HR 十二題裡只有一題落在自己的
#: 角度(「怎麼說服兩邊接受」,而那是舊的守備範圍),另外十一題有七題在
#: 技術或用人的領域——其中三題問「優先順序怎麼評估」,一題問「那個決定
#: 對不對」,後者正是當時 stance 裡寫明屬於用人主管的那一側。
#:
#: 把三十六題按問句框架分類之後看得出原因:
#:
#:                     怎麼判斷/評估   為什麼、有沒有考慮過
#:     技術主管              9                 2
#:     用人主管              0                 7
#:     HR 主管               6                 0
#:
#: 技術與用人各有一個別人不用的框架,而那兩個框架在它們的 stance 裡是**問句
#: 形狀**:「那個結論怎麼來的」、「為什麼選這個而不是那個」、「代價是什麼」。
#: HR 的四個角度全部是**題材**,沒有一個是形狀,所以它借了技術的框架——
#: 連「他為什麼做那個選擇」那一條都被吸收成「你當時怎麼決定要…」。
#:
#: 四個也太多。`_persona_block` 的註解早就記過:prompt 一長,模型只留得住
#: 最鮮明的那一個特徵。四個並列等於沒有一個鮮明。
#:
#: 所以 v4 換形式:兩個切法,加一條**過濾規則**(主詞必須是人)。過濾規則
#: 是模型可以拿去檢查自己草稿的東西,不是又一個要記住的題材。
#: 「主詞是欄位」正好就是那七題跑掉的共同特徵。
#:
#: 【訂正:當時我寫「五條追問禁令就是這樣生效的(封閉式問句一次都沒出現)」】
#: 那句話是我推的,沒有量過,而且是錯的。四次 144 題實際數下來:
#:
#:     整句就是 yes/no 的      26/144  18%
#:     含 yes/no 子句的複合題  57/144  40%
#:
#: 禁則第 2 條明文禁封閉式、第 4 條明文禁一次問兩件事,兩條都在同一支
#: prompt 裡,兩條都沒攔住。所以「禁令會生效、過濾規則也會」這個推論的
#: 前提本身不成立——而 v4 的過濾規則後來也確實被繞過了,一致。
#:
#: 留下來的結論只有一個,而它不依賴上面那句話:字面問句會傳遞
#: (v5 團隊衝突 0.477 → 0.191)。那一條是量出來的。
#:
#: 動機與合作偏好退回 routes_when 與語氣示範:回答裡有的時候仍然問得到
#: (唯一命中的那一題就是),但它們不是隨時都在的切法。
#:
#: 【HR 的守備範圍是「人」而不是某個題材,這是量出來才改的】
#: `tools/panel_role_eval.py` 第二版把同一段回答餵給三位(繞過派發),
#: 四段回答分別踩團隊衝突、數據分析、取捨決定、泛泛而談:
