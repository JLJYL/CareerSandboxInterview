"""JD 需求抽取的規則常數。

【這支存在的理由】
交接文件裡 A5 的第一步是「從 JD 抽出重視的能力與關鍵字」。D1 合約把生字串
直接交給 A,等於要她從散文反推需求,那一步被弄丟了。

成員 A 以 jobs_all.jsonl 全量實測:1,010 筆同時具備 requiredSkills 與
description 的 JD 中,5,988 條 requiredSkills 只有 332 條(5.5%)字面出現在
description 裡,82.2% 的 JD 完全沒有任何 requiredSkill 出現在散文中。

型錄職缺有結構化的 requiredSkills 可用,但**正式環境沒有**——
面試的 JD 來自 InterviewConfig.customJd,是使用者手貼的自由文字,
而且該欄位標示為選填。所以正式環境的 required_skills 只能由這支產出。

【與黃金集標記規則的一致性】
納入判準刻意採用與 label_interview_golden.py 規則四相同的問法。
兩邊不一致的話,抽取器會產出黃金集判定為「不算需求」的項目,
評測數字會怪但查不出原因。
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 納入判準
# ---------------------------------------------------------------------------

JD_INCLUSION_TEST = """判斷一段文字算不算「這份工作需要的能力」,用同一個問法:

    把這句話從 JD 刪掉,應徵條件會不會少一項?

      會                        → 納入
      不會,少的是脈絡、期待、心態 → 不納入

「負責做 X」蘊含「要會做 X」,納入。
「以某種視角看事情」是心態描述,不納入。
公司願景、產業現況、團隊文化、福利、工作環境,一律不納入。"""


JD_TRANSFERABILITY_TEST = """通過第一層之後,再問第二層:

    這個詞會出現在別家公司的職缺需求裡嗎?

      會               → 是能力,納入
      只有這一家會這樣寫  → 是職務內容,不納入

能力是可轉移的,職務內容綁在這一份工作的任務清單上。

    納入   帳務處理、SQL、專案管理、報表製作、市場分析
    排除   訂購餐點、辦公室清潔、得獎名單整理、公告上架、出貨相關事宜

第一層問「這是不是需求」,第二層問「這是不是能力」。**兩層都通過才輸出。**

判別的操作型問法:這個詞放進履歷的技能欄,看起來合不合理?
沒有人會在履歷上寫「訂購餐點」。"""


# ---------------------------------------------------------------------------
# 禁則
# ---------------------------------------------------------------------------

JD_PROHIBITIONS = """抽取時嚴禁以下五種情況:

1. 產出原文沒有依據的能力。
   不可以因為「這種職位通常需要 X」就補上 X。JD 沒提就是沒提。
   這條的重要性高於涵蓋率——寧可少抽,不可捏造。

2. 把職務內容整句照抄當成能力。
   輸出的粒度是**技能標籤**,不是句子。
   「協助建立銷售報表與資料清理」要拆成可獨立比對的短詞。

3. 產出任職條件、態度或特質,而非能力。

   門檻:學歷、年資、科系、語言檢定分數、駕照、可否配合輪班、打字速度。
   特質:主動積極、抗壓性強、細心、責任感、持續學習、良好數字概念、
         自我管理、學習能力、工作態度。
   領域:金融科技、雲端服務、電子商務——那是公司在做什麼,不是應徵者要會什麼。

   三類都不是能力,一律排除。

   判準:能力是「學得會、做得出來、可以舉例證明」的東西;
   特質是形容一個人怎麼樣,舉不出可查證的作品或成果。

   這條的重要性高於涵蓋率。特質類的項目在後續比對中幾乎必然被判成
   「沒講到」——因為人在面試裡會展現特質,不會說出特質的名稱——
   於是每一條都變成一次錯誤的指控。

4. 同一項用不同說法重複列出。
   輸出前自行去重,近義的合併成一個。

5. 改變順序。
   輸出順序即重要性順序,越前面越關鍵。下游的位置衰減權重依賴這個順序,
   重排會破壞計分。

6. 保留原文的形容詞前綴或程度修飾。
   JD 常寫「良好的溝通能力」「優秀的數字概念」「熟悉 SQL」,
   輸出時一律去掉修飾語,只留能力本身。

   「良好溝通能力」→「溝通能力」
   「熟悉 Excel」→「Excel」
   「基本會計概念」→「會計」

   理由:下游用字面比對。同一項能力因為修飾語不同而產生兩個條目,
   會被當成兩件事處理。

   **但專有名詞不可加後綴。** 去修飾語是拿掉前面的形容詞,不是在後面補說明。

       正確   C#           TypeScript      Excel
       錯誤   C#程式開發    TypeScript開發   Excel操作

   實測依據:第二版把「C#」寫成「C#程式開發」,而詞彙表的條目是「C#」,
   加了後綴就對不上,等於這條技能永遠抓不到。"""


