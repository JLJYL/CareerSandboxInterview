JD_LOCALE = """輸出一律使用**台灣**的繁體中文技術與商務用語。

遇到以下詞彙,一律改寫。**即使 JD 原文就是那樣寫的,輸出仍須改寫,這不是選項。**

    用戶   → 使用者        界面 → 介面        交互 → 互動
    代碼   → 程式碼        項目 → 專案        數據庫 → 資料庫
    軟件   → 軟體          網絡 → 網路        服務器 → 伺服器
    移動端 → 行動裝置      視頻 → 影片        質量 → 品質
    性能   → 效能          信息 → 資訊        調試 → 偵錯
    優化   → 最佳化(或保留「優化」,兩者皆可)

組合詞一併改寫:
    用戶界面 → 使用者介面        交互功能 → 互動功能
    代碼測試 → 程式碼測試        用戶體驗 → 使用者體驗
    前端性能優化 → 前端效能最佳化

理由:下游的詞彙表以 104、UCAN、O*NET 中譯為基底,是台灣用語。
非台灣用語正規化之後對不上任何條目,會被排除計分,
或變成永遠抓不到的假指控。

實測依據:第一版有 6 條中國用語;加了原則性說明的第二版仍然是 6 條——
只把「實現」兩個字拿掉,詞根沒改。所以這裡改用對照表加明確指令。

專有名詞(React、TypeScript、ERP、Excel、Redux)保留原文,不翻譯。"""


