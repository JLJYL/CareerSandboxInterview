# ---------------------------------------------------------------------------

JD_GRANULARITY = """輸出的粒度對齊人力銀行的技能標籤,不是自由描述:

    太粗   「技術能力」「軟實力」
    太細   「使用 SQL 的 GROUP BY 撰寫每週銷售彙總查詢」
    剛好   「SQL」「報表自動化」「跨部門溝通」

專有名詞保留原始拼寫與大小寫(SQL / Python / ASP.NET / C#)。
中文能力用四到八字的短詞。

一份 JD 通常抽得出 5 到 15 項。超過 25 項多半是把句子當成能力在拆,
少於 3 項多半是散文太空泛——後者是正常的,不要為了湊數而捏造。"""


# ---------------------------------------------------------------------------
# 輸出格式
# ---------------------------------------------------------------------------

JD_OUTPUT_FORMAT = """只輸出一個 JSON 陣列,不要有任何其他文字、說明或 markdown 標記。

格式:["技能一", "技能二", "技能三"]

抽不出任何能力時輸出空陣列 []。空陣列是合法答案,不要為了避免空值而捏造。"""


MAX_SKILLS = 25
"""單份 JD 的抽取上限。超過的截斷並記入 notices。

依據:黃金集裡條目最多的一份 JD 有 31 條 requiredSkills(產品行銷專案經理),
但那是 104 結構化欄位的拆解粒度。從散文抽出 25 項以上,幾乎都是把句子
當成能力在拆。"""


def compose_jd_prompt(title: str = "", company: str = "") -> str:
    """組成 system prompt。

    title 與 company 只當脈絡,不可當抽取來源——職稱叫「資料分析師」
    不代表 JD 要求「資料分析」,那是禁則第一條。
    """
    parts = [
        "你的工作是從一份職缺描述裡,抽出這份工作實際需要的能力。",
        "",
        JD_INCLUSION_TEST,
        "",
        JD_TRANSFERABILITY_TEST,
        "",
        JD_PROHIBITIONS,
        "",
        JD_LOCALE,
        "",
        JD_GRANULARITY,
        "",
        JD_OUTPUT_FORMAT,
    ]
    if title or company:
        ctx = "、".join(x for x in (title, company) if x)
        parts += [
            "",
            f"職缺脈絡(僅供理解用語,**不可**當作抽取來源):{ctx}",
        ]
    return "\n".join(parts)
