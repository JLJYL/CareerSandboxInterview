def assign_genders(n: int, seed: int) -> tuple[str, ...]:
    """按 seed 輪替指派性別。

    三個人兩種性別,每一場必然是 2:1。輪替讓同一個 persona 跨場次平均,
    所以「親切的那個總是女生」這件事在構造上就不成立。
    """
    return tuple(GENDERS[(seed + i) % len(GENDERS)] for i in range(n))


