"""群面競爭者的兩次模型呼叫:挑相鄰技能、寫人物。

【為什麼是兩次不是一次】
技能集合由程式挑(`pipeline/peer_generate.py`),理由是同質度與壓迫度可算。
但程式挑不出「分母外那幾格該放什麼」——池子裡沒有領域訊號
(152 筆的 `ucan_code` 與 `onet_code` 實測全空),所以均勻亂挑會給出
「應徵前端但會 ERP 系統與媒體關係經營」這種履歷。那一格要模型挑。

而模型挑完,程式才能排技能集合;技能集合定了,模型才能寫人物。順序是硬的:

    第一次  職缺 + 整個池子  →  相鄰技能編號清單   → 餵 plan_skills 的 off_jd_deck
    程式    plan_skills      →  每人的技能集合 + 三個指標
    第二次  技能集合 + 人格   →  名字、背景、說話風格

併成一次的話技能就不是程式挑的了,同質度會變成一次抽獎——而那正是
不把這段交給模型的全部理由。

【第一次呼叫可以按職缺快取】
同一個職缺的相鄰技能是固定的,跟是誰在面試、第幾次跑都無關。
2d 那輪的教訓是呼叫數會爆(我估 630,實跑 1710),所以這種
「每個職缺算一次就夠」的東西要一開始就設計成算一次,不是之後再優化。

【兩個 MARK 常數是給測試用的,不是裝飾】
假 LLM 依 system prompt 的子字串分派,已經誤導過三次
(1c 的決策分支、2c 的事實分支、情緒批次)。每次的症狀都一樣:
某一支收到另一支的回覆,然後測試全綠。所以每個呼叫宣告一個標記常數,
測試 import 它,prompt 改字不會讓分派靜默失效。
"""

from __future__ import annotations

from typing import Iterable, Sequence

# ---------------------------------------------------------------------------
# 第一次呼叫:挑相鄰技能
# ---------------------------------------------------------------------------

ADJACENT_MARK = "挑出這個職缺的應徵者可能也會的技能"
"""第一次呼叫的 system prompt 一定含這一段。測試依它分派。"""

ADJACENT_TARGET = 30
"""要模型挑幾個。

下限是構造需要的數量:同質度 0、壓迫度 0 的時候要 `peers × k` 個不重複的,
三位競爭者、每人六個技能 = 18 個。挑 30 留的不是安全邊際,是**多樣性**:
deck 剛好 18 的話每個 seed 都只是把同樣 18 個重排,換 seed 換不到人。

挑不到 30 不算失敗,程式會拿實際數量去對構造需求,不夠才退回亂挑。
"""

ADJACENT_TASK = f"""你在幫一個模擬面試系統準備「同場競爭者」的履歷技能。

{ADJACENT_MARK}。

這些競爭者要讓使用者覺得「這些人跟我在搶同一個位子」。
技能選得不像同一個領域的人,整個模擬就不可信——
應徵前端工程師的人不會把「媒體關係經營」寫在六個技能裡。"""

ADJACENT_RULES = f"""【規則】

1. **只能從清單裡挑**,用編號回答。清單外的一律不算,不要自己想技能名。
2. 挑**大約 {ADJACENT_TARGET} 個**。少一點可以,但不要只挑十個以內。
3. 判斷標準只有一個:**這個技能會不會跟職缺要求出現在同一份履歷上**。
   不要評分、不要排序、不要分類。
4. 職缺已經要求的那些**不要挑**,它們另外處理。
5. 寬一點比嚴一點好。相鄰不等於同一個工種——
   前端的人會 Git、也可能會 Figma 或 SQL,那些都算。
   但「ERP 系統」「媒體關係經營」不算。"""

ADJACENT_OUTPUT = """【輸出格式】

只回一個 JSON 陣列,裡面是編號整數,不要任何其他文字:

    [3, 17, 42, 58, 91]"""


def render_pool(names: Sequence[str]) -> str:
    """技能池擺成編號清單。

    【為什麼是編號不是名字】
    要模型寫名字回來,它會改寫:Adobe Photoshop → Photoshop、
    Vue.js → Vue。改寫完就對不回 skill_id,而對不回來的那幾筆會靜默消失。
    編號沒有這個問題,而且 prompt 短很多。

    這跟 2a 的指派 prompt 是同一個做法:那一輪也是編號,而且
    `followup_rate.py` 的假 LLM 第一版用整段字串比對,就因為指派 prompt
    是編號行而比不到,fallback 衝到 85.7%。
    """
    return "\n".join(f"{i}. {name}" for i, name in enumerate(names, 1))


def compose_adjacent_prompt() -> str:
    """第一次呼叫的 system prompt。

    不帶人格、不帶履歷:這一步問的是「這個職缺的相鄰技能是哪些」,
    跟誰在面試、使用者會什麼都無關。帶了只會把 prompt 撐長,
    而 1c 實測過 gpt-4o-mini 在長 prompt 下人格會塌陷。
    """
    return "\n\n".join([ADJACENT_TASK, ADJACENT_RULES, ADJACENT_OUTPUT])


def adjacent_user_message(
    title: str, required: Iterable[str], pool_names: Sequence[str]
) -> str:
    """職缺與技能池擺成 user 訊息。

    職缺要求也印出來,因為規則 4 要它避開那些。只給編號清單的話
    它會把職缺要求也挑進來,然後程式全部丟掉——等於白跑一次。
    """
    want = [w for w in required if str(w or "").strip()]
    body = [f"【職缺】{title or '(未提供職稱)'}"]
    if want:
        body.append("【職缺要求】" + "、".join(want))
    else:
        body.append("【職缺要求】(抽取失敗,沒有要求清單)")
    body += ["", "【可選技能清單】", render_pool(pool_names)]
    return "\n".join(body)


