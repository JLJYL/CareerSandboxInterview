def _persona_block(personas: tuple[PersonaSpec, ...]) -> str:
    """把 persona 設定攤成 prompt 段落。"""
    lines = ["【場上有誰】"]
    for p in personas:
        name = p.display_name or "(唯一的面試官,前端不顯示名稱)"
        lines.append(f"\n{name}")
        lines.append(f"  定位:{p.blurb}")
        lines.append(f"  行為:{p.stance}")
        if p.routes_when:
            lines.append(f"  什麼時候輪到他:{'、'.join(p.routes_when)}")
        if p.sample_lines:
            lines.append(f"  語氣示範(不要照抄):{p.sample_lines[0]}")
    return "\n".join(lines)


def compose_opening_prompt(mode: str) -> str:
    return "\n\n".join([
        "你的工作是替一場模擬面試設計開場問題。",
        LIVE_COMMON,
        _persona_block(personas_for(mode)),
        OPENING_RULES,
        OPENING_OUTPUT,
    ])


def compose_turn_prompt(mode: str, asked_questions: list[str]) -> str:
    """每輪追問的 system prompt。

    追問判準與禁則來自 probe_rules,不在這裡重寫——
    重寫會產生兩份會分岔的規則,而黃金集的標記標準也綁在那一份上。
    """
    parts = [
        "你的工作是在一場模擬面試裡,聽完對方的回答之後接話。",
        LIVE_COMMON,
        STT_CAVEAT_LIVE,
        _persona_block(personas_for(mode)),
    ]
    if mode == "panel":
        parts.append(PANEL_DISPATCH)
    elif mode == "group":
        parts.append(GROUP_DISPATCH)
    parts.append(compose_probe_rules(asked_questions))

    if mode == "single":
        parts.append(TURN_OUTPUT_SINGLE)
    else:
        names = [p.display_name for p in personas_for(mode) if p.display_name]
        parts.append(TURN_OUTPUT_MULTI)
        parts.append("【speaker 只能是這幾個】\n" + "\n".join(f"  {n}" for n in names))
    return "\n\n".join(parts)


def compose_interrupt_prompt(n: int) -> str:
    return "\n\n".join([
        "你是團體面試裡一位搶節奏的應徵者(AI-強勢)。",
        LIVE_COMMON,
        _persona_block(personas_for("group")),
        INTERRUPT_RULES.replace("{n}", str(n)),
    ])
