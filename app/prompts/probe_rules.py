"""追問生成的規則常數(A1/A2/A3 共用)。

【本檔的地位】
這裡只放規則文字,不放 prompt 本體。W2 寫 `interview_live.py` 時把這些常數
組進 system prompt。分開的理由:規則會隨調校反覆修改,prompt 骨架不會,
兩者混在一起會讓 diff 難讀。

【一條紀律】
規則一律寫成**模式**,不寫具體例句。
列舉例句會讓模型只避開那幾句,換個說法照樣違規。
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 判準:什麼情況下該追問
# ---------------------------------------------------------------------------
# 來源:InterviewProber.kt 的介面註解——
# 「由後端 LangGraph 的 evaluate_node 依回答內容(STAR 完整度、是否量化、
#   有無反思)生成追問」

PROBE_TRIGGERS = """判斷是否追問時,依序檢查回答的三項缺口:

1. STAR 完整度:情境、任務、行動、結果四段中,哪一段沒有交代。
   缺結果段最值得追問,因為那是成果的唯一證據。
2. 量化程度:回答中若只有「提升了」「變好了」這類無數字的描述,
   追問實際幅度、基準、時間範圍。
3. 反思深度:若回答只停在做了什麼,沒有交代判斷依據或事後檢討,
   追問當時如何取捨、事後會怎麼改。

三項都完整時,不要為了追問而追問,改推進到下一個主問題。"""


# ---------------------------------------------------------------------------
# 禁則:什麼不能問
# ---------------------------------------------------------------------------
# 借自參考 repo `next_question_generation` 的 Avoid 段落,改寫為模式描述。
# 這些是不寫進 prompt 就一定會發生的錯。

TRUNCATED_ANSWER = """【這段回答被語音辨識切斷了】

他還在講的時候引擎就送出了,不是他自己講完的。

    先問他還沒講完的部分,不要換新題。
    「你剛剛講到一半,後面要說的是什麼?」
    「那句話還沒說完,接著說。」

不要因為他的回答不完整而追問「為什麼沒有交代結果」——
那是責備一個被打斷的人。

也不要道歉或解釋系統的問題。面試官不會為麥克風道歉,
就當他自然停頓,請他接著講。"""


HONEST_ADMISSION = """【對方明確表示不會、沒想過、答不出來時】

換一個他答得出來的問題,不要問同一件事的變體。

    對方說「這個我沒想過」
    錯   那你在這個過程中有沒有觀察到什麼挑戰呢?   ← 同一件事換個說法
    對   沒關係,當場想。你會從哪裡開始?
    對   可以。那換個你熟的,講一個你最有把握的決定。

兩種正確做法的差別:
    第一種留在原題但降低門檻——不要求他有經驗,只問他會怎麼想
    第二種直接換題,讓他挑自己有把握的

【誠實承認不會不是扣分項】
語氣要讓他知道這件事。真實面試裡,承認不知道比硬掰有價值,
而這是練習環境,他更需要知道這一點。

不要說「沒關係」之後又追問同一個方向——那等於嘴上原諒、實際上繼續逼。

【怎麼判斷】
看的是他有沒有明確表示答不出來,不是他答得好不好。
答得含糊但有內容,那要追問;明確說不會,那要換路。"""


PROBE_PROHIBITIONS = """追問時嚴禁以下五種情況:

1. 問對方已經回答過的東西。
   已問過的問題會列給你參考。換一個說法問同一件事不算新問題。

   **這一條只約束新的主問題,不約束追問。**
   追問本來就該留在同一個話題上——那就是追問的定義。

   實測依據:早期版本把這條寫成「追問必須落在已問領域清單之外」,
   結果開場主題是「資料分析經驗」時,對方講了兩段資料分析的回答,
   模型兩輪都產不出問題——它唯一該追問的東西被禁止了。

2. 封閉式問題。
   凡是可以用是、否、或單一名詞回答完畢的問題一律不可用,
   追問必須要求對方展開敘述。
3. 誘導性問題。
   問題本身不得暗示期待的答案,不得預設對方做過某件事,
   不得把評價包裝成問句。
4. 一次問兩件以上的事。
   複合問題會讓對方只回答其中一項,另一項的缺口反而被掩蓋。
5. 詢問履歷與本場逐字稿以外可推得的私人資訊。
   包含但不限於家庭狀況、健康、政治與宗教傾向、婚育規劃。"""


# ---------------------------------------------------------------------------
# 誘導禁則的額外說明
# ---------------------------------------------------------------------------
# 這一條對面試教練特別重要,值得在 prompt 裡單獨強調。

WHY_NO_LEADING = """禁止誘導的原因:誘導式追問會讓使用者順著問題答出他其實
沒有的經歷。那份逐字稿之後要拿去做漏講點分析,虛構的內容會讓分析結果失真,
使用者會依據一份錯的報告去準備真正的面試。"""


# ---------------------------------------------------------------------------
# 追問次數上限
# ---------------------------------------------------------------------------
# 前端以 followUpIdx 控制,後端仍應自我約束,避免前端傳錯值時無限追問。

MAX_TURNS_PER_SESSION = 4
"""整場最多幾輪主要問答,超過就進入反問環節。

【這個值的語意曾經被我搞錯,更正紀錄留著】
前端的 followUpIdx **不是**「這個主問題追問了幾次」,是「整場問到第幾題」:

    InterviewLiveIndividualScreen.kt
    followUpIdx == 2 && !repeatFired  → 故意重複問一次剛剛那題(看穩定度)
    followUpIdx >= 4                  → phase = "REVERSE",進入反問環節

早期版本我寫成 MAX_FOLLOW_UP_PER_QUESTION = 1,實測六輪裡有三輪被強制推進,
對話變成「追問一次就換主題」,節奏很碎。

後端收到 follow_up_idx >= 此值時,把 should_advance 設為 True,
前端會據此進入反問環節。"""

MAX_TURNS_GROUP: int | None = None
"""群面的輪次上限。None 代表沒有上限。

【依據】
InterviewLiveGroupScreen 的 followUpIdx 只遞增,沒有任何上限檢查,
也沒有進入反問環節的邏輯——群面本來就是討論到使用者自己結束。

早期版本把一對一的 4 題上限套到群面,後果是:
選 5 人小組(7 位 persona)時只跑 5 輪,AI-親切 與 AI-沉默 永遠不會出場。
使用者選了 5 人,實際只體驗到 2 位同儕。
"""


def turn_cap_for(mode: str) -> int | None:
    """該模式的輪次上限。None 代表不限。

    一對一與 panel 走 InterviewLiveIndividualScreen 的邏輯(4 題後進反問環節);
    群面沒有上限。
    """
    return MAX_TURNS_GROUP if mode == "group" else MAX_TURNS_PER_SESSION


REPEAT_PROBE_AT = 2
"""第幾輪會故意重複問一次剛剛那題。

前端已實作(repeatFired),後端不需要處理——但要知道它存在,
否則會把那一輪的重複當成模型出錯。
那是刻意的設計:看使用者第二次講得一不一樣。"""


def compose_probe_rules(
    asked_questions: list[str], *, include_triggers: bool = True, truncated: bool = False
) -> str:
    """把規則組成可插入 system prompt 的段落。

    傳的是**已問過的問題原文**,不是領域標籤。

    【為什麼改掉標籤】
    早期版本傳領域標籤,並要求「新主問題不得重複已問領域」。
    模型滿足這條的方式是操弄標籤而不是真的換內容——實測六輪裡,
    問題問到協調排程,標籤卻回收成「資料清理經驗」。

    標籤是給前端累積用的描述性資料,不該同時當成防重複的比對鍵。
    比對真正的問題原文,模型才沒有東西可以操弄。
    """
    # include_triggers=False 時由呼叫端提供依難度而異的判準,
    # 見 app/prompts/interview_live.py 的 DIFFICULTY_TRIGGERS。
    # 兩份判準同時出現會互相打架——一份說「不要追問數字」,
    # 另一份說「無數字就追問幅度」。
    parts = ([PROBE_TRIGGERS, ""] if include_triggers else [])
    if truncated:
        # 被切斷時這條優先——先把話接完,其他判準這一輪不適用
        parts += [TRUNCATED_ANSWER, ""]
    parts += [HONEST_ADMISSION, "", PROBE_PROHIBITIONS, "", WHY_NO_LEADING]
    if asked_questions:
        listed = "\n".join(f"  {i}. {q}" for i, q in enumerate(asked_questions, 1))
        parts += [
            "",
            "【本場已經問過的問題】",
            listed,
            "",
            "換新主問題時,不要問上面任何一題的變體。追問則不受此限。",
        ]
    else:
        parts += ["", "【本場尚未問過任何問題】"]
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# 面試階段
# ---------------------------------------------------------------------------

RESUME_PHASE_TURNS = 2
"""開場之後,前幾輪的新主問題問履歷。

【為什麼要分階段】
原本沒有階段,每一輪的新主問題都是「貼著這個職位」出題,所以一場四題
全部是職缺題——使用者在應徵頁選了哪一版履歷,對話裡看不出差別。

真實面試的順序是:先自我介紹、再追你履歷上寫的、最後才問這個職缺。
這三段在問的東西不同,而我們原本只做了第三段。

【為什麼是 2】
一對一整場只有 `MAX_TURNS_PER_SESSION` 題。2 + 2 是履歷與職缺各一半。
第 `REPEAT_PROBE_AT` 題前端會刻意重複問一次看穩定度,那一題落在履歷
這一段——重複問履歷題比重複問職缺題自然。

【階段只管新主問題,不管追問】
追問該不該繼續由 `AcceptRule.max_depth` 決定,跟階段無關。
兩者混在一起的話,追問到一半會因為跨過階段邊界而被迫換題,
而那正是「鬼打牆」的相反錯誤——話講到一半被切斷。

所以階段的語意是:**當這一輪要換新主問題時,從哪個領域挑。**
面試官覺得還要再追,就繼續追,階段不攔。

【例外:每段至少一題(10/30 定案)】
上面那條讓追問一路吃掉階段:10/29 前端錄的一對一場次,開場之後四輪都在追問
自我介紹講的那件事,履歷題與職缺題都沒出現。所以每段的最後一輪還沒換過題的話,
程式強制換,見 `turn_decision.phase_switch`。其餘輪次照舊,面試官要追就追。
"""

RESUME_PHASE = """【這一段問履歷】

使用者剛剛自我介紹過,而且他選了一份履歷帶進這場面試。
換新主問題時,從**他履歷上寫的經歷**裡挑一筆來問。

挑哪一筆:跟這個職缺最相關的那一筆優先。他自我介紹時提過的那一筆次之——
他主動提代表他準備好要講,先問別的反而浪費。

【只能問履歷上寫了的事】
履歷沒寫的不要問得像他做過。「你在帶團隊的時候…」如果履歷上沒有帶人的
經歷,那句話預設了一件沒有發生的事,他只能順著你的假設編,或者花時間澄清。
兩種都是我們造成的。

【不要把履歷唸回去】
「你履歷上寫你做過 X,可以說說嗎」這種問法等於要他把寫過的再講一次。
問的要是履歷上**沒有寫的那一層**:當時為什麼那樣做、卡在哪裡、
如果重來會改什麼。"""

JD_PHASE = """【這一段問職缺】

履歷那一段問完了。換新主問題時,改問這個**職缺本身**會遇到的事。

可以問:這個職位的日常工作他會怎麼處理、職缺要求的能力他有沒有對應的
依據、他對這個領域的判斷。

【不要再回頭問履歷】
前面已經問過了。回頭問會變成同一件事問兩次,而使用者會覺得你沒在聽。"""


NO_RESUME_PHASE = """【這一段本來問履歷,但他沒有帶履歷】

使用者沒有選履歷,所以沒有具體經歷可以指名問。這一段改用職缺的能力出題。

換新主問題時,從上面【職位脈絡】列的能力裡挑一個這場還沒問到的,
再用他剛剛講過的事當切入點接過去。

【不要問得像你看過他的履歷】
「你上一份工作…」「你在帶團隊的時候…」這種問法預設了沒有發生的事。
他只能順著你的假設編,或者花時間澄清——兩種都是我們造成的。
只問他自己講出來的東西。"""


def interview_phase(turn_index: int, has_resume: bool = True) -> str:
    """這一輪換新主問題的話,要問哪一段。

    `turn_index` 是整場問到第幾輪(前端的 followUpIdx,從 0 起算)。

    【為什麼用 followUpIdx 而不是「第幾個主問題」】
    後端是無狀態的,算得出來的只有前端帶回來的東西,而「這是第幾個主問題」
    沒有欄位帶。followUpIdx 是現成的,而且 `must_advance` 已經在用它。

    代價:追問會吃掉階段的額度。困難難度追三次的話,履歷那一段只問得到
    一個主問題。那是可以接受的——使用者說的是「面試官覺得有需要可以繼續
    追問」,那就表示追問優先於階段進度。10/30 起每段至少保留一題,
    見 `RESUME_PHASE_TURNS` 的例外那一節。

    【沒有履歷時給的是另一段,不是不給】
    原本的寫法是呼叫端判斷「這是履歷段而且沒有履歷,那就整段不要給」。
    不叫它去編一筆經歷是對的,但那樣前兩輪就**完全沒有**換題的材料。

    `data/panel_next_v1.json`(36 筆,決定全部指定成 NEXT)量到的差別:

                            通用的「有沒有遇到什麼挑戰」   引用回答
        沒有階段區塊(0-1)          12/18                1/18
        有 JD_PHASE  (2-3)           3/18                5/18

    同一句 NEXT 指令,有材料的時候照著做,沒材料的時候退回通用問句。
    所以缺的不是指令寫得不夠好,是那兩輪手上沒有東西可挑。

    【為什麼判斷搬進來】
    「哪一段適用」原本一半在這個函式、一半在 `compose_turn_prompt` 的
    `if phase is not RESUME_PHASE or has_resume`。拆成兩半的結果就是
    上面那個洞:函式回了履歷段,呼叫端把它丟掉,然後沒有人補。
    """
    if turn_index >= RESUME_PHASE_TURNS:
        return JD_PHASE
    return RESUME_PHASE if has_resume else NO_RESUME_PHASE
